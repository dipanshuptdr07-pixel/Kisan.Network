function translateDynamic(
  text: string,
  language: Language
): string | undefined {
  if (language === 'hi') {
    let match = text.match(/^Try again in (\d+)s$/);
    if (match) return `${match[1]} सेकंड बाद फिर कोशिश करें`;

    match = text.match(/^Good morning, (.+)\.$/);
    if (match) return `सुप्रभात, ${match[1]} जी।`;

    match = text.match(/^Consultation request started for (.+)\.$/);
    if (match) return `${match[1]} के लिए परामर्श का अनुरोध शुरू हुआ।`;

    match = text.match(/^Enquiry sent for (.+)\.$/);
    if (match) return `${match[1]} के लिए पूछताछ भेजी गई।`;

    match = text.match(/^Order (KN-\d+) details opened\.$/);
    if (match) return `ऑर्डर ${match[1]} का विवरण खुल गया।`;

    match = text.match(/^View (KN-\d+)$/);
    if (match) return `${match[1]} देखें`;

    match = text.match(/^(.+) added to your crops\.$/);
    if (match) return `आपकी फ़सल सूची में ${match[1]} जोड़ दी गई।`;

    match = text.match(/^(.+) details opened in demo\.$/);
    if (match) return `डेमो में ${match[1]} की जानकारी खुल गई।`;

    match = text.match(/^Opening “(.+)”\.$/);
    if (match) return `“${match[1]}” खुल रहा है।`;

    match = text.match(/^Consultation details opened for (.+)\.$/);
    if (match) return `${match[1]} के परामर्श का विवरण खुल गया।`;

    match = text.match(/^(\d+(?:\.\d+)?) acres$/);
    if (match) return `${match[1]} एकड़`;

    match = text.match(/^([\d.]+) acres · (.+)$/);
    if (match) {
      return `${match[1]} एकड़ · ${hindi[match[2]] || match[2]}`;
    }

    match = text.match(/^(\d+) min$/);
    if (match) return `${match[1]} मिनट`;

    match = text.match(/^(\d+) min read$/);
    if (match) return `${match[1]} मिनट पढ़ने का समय`;

    match = text.match(/^([+-]?\d+(?:\.\d+)?)% this week$/);
    if (match) return `इस सप्ताह ${match[1]}%`;

    match = text.match(/^([+-]?\d+(?:\.\d+)?)%$/);
    if (match) return `${match[1]}%`;

    match = text.match(/^(\d+) farmers reached$/);
    if (match) return `${match[1]} किसानों तक पहुँचा`;

    match = text.match(/^(\d+) farmers$/);
    if (match) return `${match[1]} किसान`;

    match = text.match(/^(\d+) demo accounts · (\d+) public roles$/);
    if (match) {
      return `${match[1]} डेमो खाते · ${match[2]} सार्वजनिक भूमिकाएँ`;
    }

    match = text.match(/^(\d+) indicative prices · (\d+) sample orders$/);
    if (match) {
      return `${match[1]} सांकेतिक भाव · ${match[2]} नमूना ऑर्डर`;
    }

    match = text.match(/^(.+) · ₹([\d,]+) \/ (quintal|qtl)$/);
    if (match) {
      return `${hindi[match[1]] || match[1]} · ₹${match[2]} / क्विंटल`;
    }
  } else {
    let match = text.match(/^सुप्रभात, (.+?) जी।$/);
    if (match) return `Good morning, ${match[1]}.`;

    match = text.match(/^(\d+) सेकंड बाद फिर कोशिश करें$/);
    if (match) return `Try again in ${match[1]}s`;

    match = text.match(/^(\d+(?:\.\d+)?) एकड़$/);
    if (match) return `${match[1]} acres`;

    match = text.match(/^(\d+) मिनट$/);
    if (match) return `${match[1]} min`;

    match = text.match(/^(\d+) मिनट पढ़ने का समय$/);
    if (match) return `${match[1]} min read`;

    match = text.match(/^इस सप्ताह ([+-]?\d+(?:\.\d+)?)%$/);
    if (match) return `${match[1]}% this week`;

    match = text.match(/^([+-]?\d+(?:\.\d+)?)%$/);
    if (match) return `${match[1]}%`;

    match = text.match(/^(\d+) किसान$/);
    if (match) return `${match[1]} farmers`;

    match = text.match(/^(\d+) किसानों तक पहुँचा$/);
    if (match) return `${match[1]} farmers reached`;

    match = text.match(/^ऑर्डर (KN-\d+) का विवरण खुल गया।$/);
    if (match) return `Order ${match[1]} details opened.`;
  }

  const dateMatch = text.match(
    /^(Monday|Tuesday|Wednesday|Thursday|Friday|Saturday|Sunday), (\d{1,2}) (January|February|March|April|May|June|July|August|September|October|November|December)$/
  );

  if (dateMatch) {
    if (language === 'hi') {
      const weekdays: Record<string, string> = {
        Monday: 'सोमवार',
        Tuesday: 'मंगलवार',
        Wednesday: 'बुधवार',
        Thursday: 'गुरुवार',
        Friday: 'शुक्रवार',
        Saturday: 'शनिवार',
        Sunday: 'रविवार',
      };

      const months: Record<string, string> = {
        January: 'जनवरी',
        February: 'फ़रवरी',
        March: 'मार्च',
        April: 'अप्रैल',
        May: 'मई',
        June: 'जून',
        July: 'जुलाई',
        August: 'अगस्त',
        September: 'सितंबर',
        October: 'अक्टूबर',
        November: 'नवंबर',
        December: 'दिसंबर',
      };

      return `${weekdays[dateMatch[1]]}, ${dateMatch[2]} ${months[dateMatch[3]]}`;
    }

    const hindiWeekdays: Record<string, string> = {
      सोमवार: 'Monday',
      मंगलवार: 'Tuesday',
      बुधवार: 'Wednesday',
      गुरुवार: 'Thursday',
      शुक्रवार: 'Friday',
      शनिवार: 'Saturday',
      रविवार: 'Sunday',
    };

    const hindiMonths: Record<string, string> = {
      जनवरी: 'January',
      फ़रवरी: 'February',
      मार्च: 'March',
      अप्रैल: 'April',
      मई: 'May',
      जून: 'June',
      जुलाई: 'July',
      अगस्त: 'August',
      सितंबर: 'September',
      अक्टूबर: 'October',
      नवंबर: 'November',
      दिसंबर: 'December',
    };

    const reverseDate = text.match(
      /^(सोमवार|मंगलवार|बुधवार|गुरुवार|शुक्रवार|शनिवार|रविवार), (\d{1,2}) (जनवरी|फ़रवरी|मार्च|अप्रैल|मई|जून|जुलाई|अगस्त|सितंबर|अक्टूबर|नवंबर|दिसंबर)$/
    );

    if (reverseDate) {
      return `${hindiWeekdays[reverseDate[1]]}, ${reverseDate[2]} ${hindiMonths[reverseDate[3]]}`;
    }
  }

  return undefined;
}

export function translateText(
  source: string,
  language: Language
): string {
  const leading = source.match(/^\s*/)?.[0] || '';
  const trailing = source.match(/\s*$/)?.[0] || '';
  const text = source.trim();

  if (!text) return source;

  let translated: string | undefined;

  if (language === 'hi') {
    translated = hindi[text] ?? translateDynamic(text, language);
  } else {
    translated =
      englishByHindi.get(text) ?? translateDynamic(text, language);
  }

  if (!translated) {
    return source;
  }

  return `${leading}${translated}${trailing}`;
}